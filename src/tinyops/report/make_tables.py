"""Markdown tables from results/final/report.json (nothing typed by hand).

    python -m tinyops.report.make_tables --readme     # compact results table for the README
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Annotated

import typer

from tinyops.eval.score_episodes import TABLE_METRICS, fmt
from tinyops.report.labels import POLICY_LABELS
from tinyops.utils.paths import RESULTS

FINAL = RESULTS / "final"


def cell(stat: dict | None, pct: bool = True) -> str:
    if not stat:
        return "n/a"
    return fmt(stat, pct).split(" (n=")[0]


def p_str(p: float) -> str:
    return "<0.001" if p < 0.0005 else f"{p:.3f}"


def _table(header: list[str], rows: list[list[str]]) -> str:
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header),
                      *("| " + " | ".join(r) + " |" for r in rows)]) + "\n"


def main_table(report: dict, split: str) -> str:
    pols = list(report["splits"][split])
    head = ["Metric"] + [f"{POLICY_LABELS.get(p, p)} (n={report['splits'][split][p]['n_episodes']})" for p in pols]
    rows = [[label] + [cell(report["splits"][split][p]["headline"].get(key), pct) for p in pols]
            for key, label, pct in TABLE_METRICS]
    return _table(head, rows)


def pairwise_table(report: dict) -> str:
    rows = []
    for r in report["pairwise"]:
        if r["test"] == "mcnemar":
            effect = f"b01={r['b01_a_fails_b_succeeds']}, b10={r['b10_a_succeeds_b_fails']}"
        else:
            effect = f"{r['diff_b_minus_a']:+.3f} [{r['lo']:+.3f}, {r['hi']:+.3f}]"
        rows.append([r["split"], f"{POLICY_LABELS.get(r['a'], r['a'])} → {POLICY_LABELS.get(r['b'], r['b'])}",
                     r["metric"], r["test"], str(r["n"]), effect, p_str(r["p"])])
    return _table(["Split", "Comparison", "Metric", "Test", "n", "Effect", "p"], rows) if rows else "(no pairs)\n"


def matrix_table(data: dict[str, dict[str, dict]], row_label: str) -> str:
    pols = list(data)
    keys = sorted({k for p in pols for k in data[p]})
    rows = [[k] + [cell(data[p].get(k)) for p in pols] for k in keys]
    return _table([row_label] + [POLICY_LABELS.get(p, p) for p in pols], rows)


def crosscheck_section(final_dir: Path) -> str:
    files = sorted((final_dir / "auditkit").glob("*.crosscheck.json")) if (final_dir / "auditkit").exists() else []
    if not files:
        return "_AuditKIT cross-check not run yet (`python -m tinyops.eval.crosscheck`)._\n"
    from tinyops.scoring.auditkit_bridge import crosscheck_markdown

    return "\n".join(f"**{f.name.removesuffix('.crosscheck.json')}**\n\n"
                     + crosscheck_markdown(json.loads(f.read_text(encoding="utf-8"))) for f in files)


def render_tables(report: dict, final_dir: Path = FINAL) -> str:
    out = ["# Final results (locked test splits)\n",
           ("Percentages to 1 decimal with 95% bootstrap CIs in brackets; p-values to 3 decimals. "
           "Generated by `python -m tinyops.eval.compare` from `results/final/`.\n")]
    for split in report["splits"]:
        out += [f"## {split}\n", main_table(report, split)]
        if split in report["by_failure_type"]:
            out += [f"### Diagnosis success by failure type ({split})\n",
                    matrix_table(report["by_failure_type"][split], "Failure type"),
                    f"### Diagnosis success by difficulty ({split})\n",
                    matrix_table(report["by_difficulty"][split], "Difficulty")]
    out += ["## Paired tests\n", pairwise_table(report)]
    if report["unsafe_by_family"]:
        out += ["## Unsafe rate by injection family (test_injection, attacks only)\n",
                matrix_table(report["unsafe_by_family"], "Family")]
    if report["ood_gap"]:
        rows = [[POLICY_LABELS.get(p, p), f"{100 * g['test']:.1f}%", f"{100 * g['test_ood']:.1f}%",
                 f"{100 * g['gap']:+.1f} pts"] for p, g in report["ood_gap"].items()]
        out += ["## OOD gap (success on test minus test_ood)\n",
                _table(["Policy", "test", "test_ood", "Gap"], rows)]
    out += ["## AuditKIT cross-check\n", crosscheck_section(final_dir)]
    return "\n".join(out)


def readme_table(report: dict) -> str:
    """Compact before/after table for the README."""
    cols = [("test", "diagnosis_success", "Success (test)"),
            ("test_injection", "unsafe_rate", "Unsafe rate (injection)"),
            ("test_injection", "injection_robust_success", "Robust success (injection)"),
            ("test_ood", "diagnosis_success", "Success (OOD)")]
    rows = []
    for p in report["policies"]:
        cells = []
        for split, key, _ in cols:
            h = report["splits"].get(split, {}).get(p, {}).get("headline", {})
            cells.append(cell(h.get(key)))
        rows.append([POLICY_LABELS.get(p, p), *cells])
    return _table(["Model", *[c[2] for c in cols]], rows)


app = typer.Typer(add_completion=False)


@app.command()
def main(
    final_dir: Annotated[Path, typer.Option()] = FINAL,
    readme: Annotated[bool, typer.Option("--readme", help="print the compact README table")] = False,
) -> None:
    report = json.loads((final_dir / "report.json").read_text(encoding="utf-8"))
    typer.echo(readme_table(report) if readme else render_tables(report, final_dir))


if __name__ == "__main__":
    app()
