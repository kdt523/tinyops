"""Draft model card for the SFT adapter. Numbers come only from result files; missing = stated."""

from __future__ import annotations

from pathlib import Path
from typing import Annotated

import typer

from tinyops.eval.score_episodes import fmt
from tinyops.utils.io import read_json
from tinyops.utils.paths import RESULTS, ROOT

ROWS = [("diagnosis_success", "Diagnosis success", True), ("format_valid_rate", "Format valid", True),
        ("schema_valid_rate", "Schema valid", True), ("unsafe_rate", "Unsafe rate (attacks)", True),
        ("redundant_calls_per_ep", "Redundant calls / ep", False)]
PENDING = "_not evaluated yet_"


def _row(metrics: dict | None, key: str, pct: bool) -> str:
    return PENDING if metrics is None else fmt(metrics["headline"][key], pct)


def render_sft_card(cfg: dict, stats: dict | None, selection: dict | None,
                    sft_val: dict | None, base_val: dict | None, fewshot_val: dict | None,
                    repo_id: str = "<user>/tinyops-tiny-aya-sft") -> str:
    lora = cfg["lora"]
    table = ["| Metric (val, n=180) | Base zero-shot | Base few-shot | SFT adapter |", "|---|---|---|---|"]
    for key, label, pct in ROWS:
        table.append(f"| {label} | {_row(base_val, key, pct)} | {_row(fewshot_val, key, pct)} | "
                     f"{_row(sft_val, key, pct)} |")
    data = (f"{stats['examples']} multi-turn gold conversations ({stats['tokens']} tokens, "
            f"{100 * stats['injected_attack_share']:.1f}% with an injected instruction, "
            f"{100 * stats['benign_lookalike_share']:.1f}% harmless lookalikes, "
            f"{100 * stats['teacher_share']:.0f}% teacher-generated)") if stats else PENDING
    chosen = (f"step {selection['chosen']['step']} "
              f"(val subset success {selection['chosen']['diagnosis_success']:.3f}, "
              f"safety constraint met: {selection['constraint_met']})") if selection else PENDING
    return f"""---
license: cc-by-nc-4.0
base_model: CohereLabs/tiny-aya-global
library_name: peft
tags: [lora, tool-use, kubernetes, agent, safety, sft]
---
# {repo_id}  (SFT stage, draft)

LoRA adapter for **CohereLabs/tiny-aya-global** that makes the model call Kubernetes incident-response
tools correctly and ignore instructions hidden in tool output. Trained in a **simulated** cluster
(KubeSim) for research; not validated on real clusters.

## Training
- Method: supervised fine-tuning, assistant-only loss, LoRA r={lora['r']} alpha={lora['alpha']}
  dropout={lora['dropout']} on all linear layers; lr {cfg['lr']}, {cfg['epochs']} epochs, effective
  batch {cfg['per_device_batch'] * cfg['grad_accum']}, max length {cfg['max_seq_len']}, seed {cfg['seed']}.
- Data: {data}. Generated by `python -m tinyops.scenarios.build_dataset` (seed 1234); the test splits were never used.
- Selected checkpoint: {chosen}.

## Evaluation (greedy decoding, KubeSim, 8 steps max)
{chr(10).join(table)}

Metrics are produced by `python -m tinyops.eval.score_episodes` and read from `results/metrics/`.
The final test-split results belong to the final model card.

## Limitations
Simulated environment; keyword-based diagnosis matcher (agreement with an LLM judge not measured);
English only; one model size.

## Licence and credits
Base model: Tiny Aya, CC-BY-NC (gated). Training code: AgentTune (LSAL v1.1); evaluation: AuditKIT
(LSAL v1.2). Research and hackathon use only.

## Load
```python
from transformers import AutoTokenizer, AutoModelForCausalLM
from peft import PeftModel
base = AutoModelForCausalLM.from_pretrained("CohereLabs/tiny-aya-global", dtype="auto", device_map="auto")
model = PeftModel.from_pretrained(base, "{repo_id}")
tok = AutoTokenizer.from_pretrained("CohereLabs/tiny-aya-global")
```
"""


def _maybe(path: Path) -> dict | None:
    return read_json(path) if path.exists() else None


def main(
    config: Annotated[Path, typer.Option()] = ROOT / "configs" / "sft.yaml",
    results: Annotated[Path, typer.Option()] = RESULTS,
    out: Annotated[Path, typer.Option()] = ROOT / "hub" / "model_card_sft.md",
    repo_id: Annotated[str, typer.Option()] = "<user>/tinyops-tiny-aya-sft",
) -> None:
    from tinyops.train.sft import load_config

    cfg = load_config(config)
    run = _maybe(results / "runs" / "sft_train_run.json")
    card = render_sft_card(
        cfg, run["dataset_stats"] if run else _maybe(results / "runs" / "sft_dataset_stats.json"),
        _maybe(results / "runs" / "sft_selection.json"), _maybe(results / "metrics" / "sft_val.json"),
        _maybe(results / "metrics" / "tinyaya_zeroshot_val.json"),
        _maybe(results / "metrics" / "tinyaya_fewshot_val.json"), repo_id)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(card, encoding="utf-8")


if __name__ == "__main__":
    typer.run(main)
